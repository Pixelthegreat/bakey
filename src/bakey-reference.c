/*
 * This is the standard reference implementation for
 * bakey. Though it uses SDL like the proper SDL
 * implementation, it lacks many features including:
 *  - A child shell process
 *  - Configuration of any kind
 *
 * This is purely intended as a guide for anyone who
 * wants to learn how a bakey implementation works or
 * wants to make one.
 *
 * When you run this implementation, you should get a
 * message like:
 *  'PTS path: /dev/pts/1'
 * Keep that path in mind. If you wish to run a shell
* inside this implementation, run a command similar
 * to the following:
 *  'sh </dev/pts/1 >/dev/pts/1 2>/dev/pts/1'
 * But replace '/dev/pts/1' with the path you were
 * given.
 */
