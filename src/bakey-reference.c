/*
 * Called when Bakey is initialized
 *
 * This function opens a pseudo-terminal using
 * posix_openpt, grantpt and unlockpt. It then opens a
 * slave connection to the terminal to ensure that it
 * stays open even if nothing else is connected. Lastly
 * it sets the terminal size using the TIOCSWINSZ
 * ioctl, and prints the path of the pseudo-terminal.
 */
static bakey_result_t term_open(void) {

	pty = posix_openpt(O_RDWR | O_NOCTTY);
	if (pty < 0) {

		perror("posix_openpt");
		return BAKEY_RESULT_FAILURE;
	}
	if (grantpt(pty) < 0) {

		perror("grantpt");
		return BAKEY_RESULT_FAILURE;
	}
	if (unlockpt(pty) < 0) {

		perror("unlockpt");
		return BAKEY_RESULT_FAILURE;
	}

	/*
	 * Open slave connection
	 */
	const char *path = ptsname(pty);
	spty = open(path, O_RDWR);

	if (spty < 0) {

		perror("open");
		return BAKEY_RESULT_FAILURE;
	}

	/*
	 * Set terminal window size
	 */
	struct winsize winsize = {
		.ws_row = (unsigned short)display.height,
		.ws_col = (unsigned short)display.width,
		.ws_xpixel = WIDTH,
		.ws_ypixel = HEIGHT,
	};
	if (ioctl(pty, TIOCSWINSZ, &winsize) < 0) {

		perror("ioctl(TIOCSWINSZ)");
		return BAKEY_RESULT_FAILURE;
	}

	printf("PTY path: %s\n", path);
	return BAKEY_RESULT_SUCCESS;
}

/*
 * Read from terminal
 */
static size_t term_read(void *buffer, size_t count) {

	int nread = read(pty, buffer, count);
	return nread < 0? 0: (size_t)nread;
}

/*
 * Write to terminal
 */
static size_t term_write(const void *buffer, size_t count) {

	int nwritten = write(pty, buffer, count);
	return nwritten < 0? 0: (size_t)nwritten;
}

/*
 * Close terminal
 */
static void term_close(void) {

	if (spty >= 0) close(spty);
	if (pty >= 0) close(pty);
}

/*
 * Frame timer callback (signal handler for SIGALRM)
 *
 * This sets the draw flag and also breaks out of any
 * call to read that might be happening.
 */
static void sigh_alrm() {

	draw = true;
}

/*
 * Interpret event
 */
static void process_event(SDL_Event *event) {

	if (event->type == SDL_QUIT)
		running = false;

	else if (event->type == SDL_KEYDOWN || event->type == SDL_KEYUP) {

		if (event->key.keysym.sym == SDLK_LSHIFT ||
		    event->key.keysym.sym == SDLK_RSHIFT) {

			shifted = (event->type == SDL_KEYDOWN);
			return;
		}
		else if (event->key.keysym.sym == SDLK_LCTRL ||
			 event->key.keysym.sym == SDLK_RCTRL) {

			ctrled = (event->type == SDL_KEYDOWN);
			return;
		}
		else if (event->type != SDL_KEYDOWN)
			return;

		/*
		 * Control modifier
		 */
		else if (ctrled) {

			wchar_t wc = (wchar_t)towupper((wchar_t)event->key.keysym.sym);

			if (wc >= L'A' && wc <= L'Z')
				bakey_send_character(&context, wc - L'A' + 1);
			return;
		}

		/*
		 * Miscellaneous special keys
		 */
		switch (event->key.keysym.sym) {

			case SDLK_BACKSPACE: bakey_send_character(&context, L'\x7f'); break;
			case SDLK_TAB: bakey_send_character(&context, L'\t'); break;
			case SDLK_RETURN: bakey_send_character(&context, L'\r'); break;
			case SDLK_ESCAPE: bakey_send_character(&context, L'\x1b'); break;
			case SDLK_UP: bakey_send_sequence(&context, L"\x1b[A"); break;
			case SDLK_DOWN: bakey_send_sequence(&context, L"\x1b[B"); break;
			case SDLK_RIGHT: bakey_send_sequence(&context, L"\x1b[C"); break;
			case SDLK_LEFT: bakey_send_sequence(&context, L"\x1b[D"); break;
		}
	}
	else if (event->type == SDL_TEXTINPUT) {

		for (size_t i = 0; i < SDL_TEXTINPUTEVENT_TEXT_SIZE &&
				   event->text.text[i]; i++) {

			wchar_t wc;
			int nch = mbtowc(&wc, event->text.text+i, MB_CUR_MAX);
			if (nch < 1) continue;
			i += nch-1;

			bakey_send_character(&context, wc);
		}
	}
}

/*
 * Draw the terminal screen
 *
 * set_color is a simple helper function that
 * translates a bakey color to R8 G8 B8 values.
 */
static void set_color(bakey_color_t color, bool set_texture_mod) {

	if (!set_texture_mod) {

		SDL_SetRenderDrawColor(renderer,
				       (uint8_t)((color >> 16) & 0xff),
				       (uint8_t)((color >> 8) & 0xff),
				       (uint8_t)(color & 0xff),
				       0xff);
	}
	else {
		SDL_SetTextureColorMod(font_atlas_texture,
				       (uint8_t)((color >> 16) & 0xff),
				       (uint8_t)((color >> 8) & 0xff),
				       (uint8_t)(color & 0xff));
	}
}

#define SWAP_VALUES(a, b) ({\
		a ^= b;\
		b ^= a;\
		a ^= b;\
	})

static void draw_terminal(void) {

	SDL_SetRenderDrawColor(renderer, 0, 0, 0, 0xff);
	SDL_RenderClear(renderer);

	for (size_t y = 0; y < display.height; y++) {
		for (size_t x = 0; x < display.width; x++) {

			bakey_cell_t *cell = display.cells + y * display.width + x;
			if (cell->character > FONT_COUNT) /* ignoring a character if it is out of the ASCII range */
				continue;

			size_t dx = x * FONT_SPACING;
			size_t dy = y * FONT_HEIGHT;
			size_t sx = ((size_t)cell->character % 16) * FONT_WIDTH;
			size_t sy = ((size_t)cell->character / 16) * FONT_HEIGHT;

			/*
			 * We first determine the
			 * foreground and background
			 * colors. BAKEY_STYLE_INVERSE
			 * is currently the only style
			 * flag this implementation
			 * supports.
			 */
			bakey_color_t background = cell->background;
			bakey_color_t foreground = cell->foreground;

			if (cell->style & BAKEY_STYLE_INVERSE)
				SWAP_VALUES(background, foreground);

			if (context.position == y * display.width + x) /* cursor position */
				SWAP_VALUES(background, foreground);

			/*
			 * Then we draw the background
			 * and the character.
			 */
			SDL_Rect dest = {
				(int)dx, (int)dy,
				FONT_SPACING,
				FONT_HEIGHT,
			};
			SDL_Rect source = {
				(int)sx, (int)sy,
				FONT_WIDTH,
				FONT_HEIGHT,
			};

			set_color(background, false);
			SDL_RenderFillRect(renderer, &dest);
			dest.w = FONT_WIDTH;

			if (cell->character) {

				set_color(foreground, true);
				SDL_RenderCopy(renderer, font_atlas_texture, &source, &dest);
			}
		}
	}
}

/*
 * Run the main application
 */
static int run(void) {

	/*
	 * First off, we configure the environment.
	 *
	 * For setlocale: Bakey uses the multibyte
	 * encoding functions, which need a non-default
	 * locale to be set. For that purpose,
	 * en_US.UTF8 should work just fine.
	 *
	 * For sigaction: We use sigaction instead of
	 * signal here because in my testing, calls to
	 * read do not get interrupted by signals that
	 * were configured with the older function.
	 *
	 * For setenv: Setting the TERM environment
	 * variable to 'vt100' ensures that whatever
	 * was in the TERM variable before will not
	 * have any influence on what different
	 * programs think the capabilities of Bakey
	 * are.
	 */
	setlocale(LC_ALL, "en_US.UTF8");

	struct sigaction action;

	action.sa_handler = sigh_alrm;
	sigemptyset(&action.sa_mask);
	action.sa_flags = 0;
	action.sa_restorer = NULL;

	if (sigaction(SIGALRM, &action, NULL)) {

		perror("sigaction");
		return 1;
	}

	setenv("TERM", "vt100-bakey", 1);
#ifdef DEBUG
	static char termpathbuf[PATH_MAX];
	realpath("./terminfo", termpathbuf);

	setenv("TERMINFO", termpathbuf, 1);
#endif

	/*
	 * Next we need to initialize SDL, create a
	 * window and create a renderer. I won't say
	 * much about this since it's all very well
	 * documented elsewhere.
	 *
	 * The SDL_HINT_NO_SIGNAL_HANDLERS hint just
	 * tells SDL to not bother installing its own
	 * signal handlers for anything.
	 */
	SDL_SetHint(SDL_HINT_NO_SIGNAL_HANDLERS, "1");
	if (SDL_Init(SDL_INIT_EVERYTHING) < 0) {

		fprintf(stderr, "SDL: %s\n", SDL_GetError());
		return 1;
	}
	init_sdl = true;

	window = SDL_CreateWindow(TITLE,
				  SDL_WINDOWPOS_UNDEFINED,
				  SDL_WINDOWPOS_UNDEFINED,
				  WIDTH,
				  HEIGHT,
				  SDL_WINDOW_ALLOW_HIGHDPI);
	if (!window) {

		fprintf(stderr, "SDL: %s\n", SDL_GetError());
		return 1;
	}

	renderer = SDL_CreateRenderer(window, -1, 0);
	if (!renderer) {

		fprintf(stderr, "SDL: %s\n", SDL_GetError());
		return 1;
	}

	/*
	 * Here we create the font atlas. The font size
	 * is technically 9x16, but each row of each
	 * character can actually be represented as
	 * 8 pixels.
	 *
	 * First we create an RGB surface and convert
	 * from the 1bpp format that our font data is
	 * in to an 32bpp format that SDL will
	 * understand. Then, we convert the surface to
	 * a texture and free it.
	 */
	SDL_Surface *surface = SDL_CreateRGBSurface(0,
						    FONT_WIDTH * 16,
						    FONT_HEIGHT * 16,
						    32,
						    0x00ff0000,
						    0x0000ff00,
						    0x000000ff,
						    0xff000000);
	if (!surface) {

		fprintf(stderr, "SDL: %s\n", SDL_GetError());
		return 1;
	}

	SDL_LockSurface(surface);

	for (int i = 0; i < FONT_COUNT; i++) {

		int x = i % 16;
		int y = i / 16;

		uint8_t *wdata = (uint8_t *)surface->pixels +
				 y * FONT_HEIGHT * surface->pitch +
				 x * FONT_WIDTH * 4;

		uint8_t *rdata = font_data + i * FONT_HEIGHT;

		for (int py = 0; py < FONT_HEIGHT; py++) {
			for (int px = 0; px < FONT_WIDTH; px++) {

				uint8_t value = ((rdata[py] >> (8 - px)) & 0x1) * 0xff; /* reads a bit from the bitset */

				wdata[py * surface->pitch + px * 4] = 0xff;
				wdata[py * surface->pitch + px * 4 + 1] = 0xff;
				wdata[py * surface->pitch + px * 4 + 2] = 0xff;
				wdata[py * surface->pitch + px * 4 + 3] = value;
			}
		}
	}

	SDL_UnlockSurface(surface);

	font_atlas_texture = SDL_CreateTextureFromSurface(renderer, surface);
	SDL_FreeSurface(surface);

	if (!font_atlas_texture) {

		fprintf(stderr, "SDL: %s\n", SDL_GetError());
		return 1;
	}

	/*
	 * The last thing to do before the main loop
	 * is initialize Bakey. Before we do this, we
	 * calculate the size of the Bakey terminal
	 * display and allocate the character cells.
	 * We are fully responsible for managing the
	 * display cells, meaning reallocating them
	 * when necessary (if we allow resizing), and
	 * freeing them at the end.
	 */
	display.width = WIDTH / FONT_SPACING;
	display.height = HEIGHT / FONT_HEIGHT;
	display.cells = malloc(sizeof(bakey_cell_t) * display.width * display.height);

	if (bakey_open(&context) != BAKEY_RESULT_SUCCESS) {

		fprintf(stderr, "Bakey: %s\n", bakey_get_error());
		return 1;
	}

	/*
	 * I lied, the actual last thing is to setup
	 * the frame timer.
	 */
	struct itimerval it = {
		.it_interval = {
			.tv_sec = 0,
			.tv_usec = 1000000 / FPS_CAP,
		},
		.it_value = {
			.tv_sec = 0,
			.tv_usec = 1000000 / FPS_CAP,
		},
	};
	setitimer(ITIMER_REAL, &it, NULL);

	/*
	 * == Main Loop ==
	 */
	SDL_Event event;

	while (running) {

		/*
		 * While this is sort of crude and
		 * probably bad for performance, we
		 * check for updates in terminal
		 * attributes every cycle of the main
		 * loop, and update the appropriate
		 * values for the Bakey context.
		 */
		struct termios attr;
		if (tcgetattr(pty, &attr) >= 0) {

			if (attr.c_lflag & ECHO)
				context.control.flags |= BAKEY_CONTROL_FLAG_ECHO;
			else context.control.flags &= ~BAKEY_CONTROL_FLAG_ECHO;

			if (attr.c_lflag & ICANON)
				context.control.flags |= BAKEY_CONTROL_FLAG_CANONICAL;
			else context.control.flags &= ~BAKEY_CONTROL_FLAG_CANONICAL;

			if (attr.c_lflag & ISIG)
				context.control.flags |= BAKEY_CONTROL_FLAG_SIGNAL;
			else context.control.flags &= ~BAKEY_CONTROL_FLAG_SIGNAL;

			context.control.cc[BAKEY_CONTROL_CHARACTER_MINIMUM] = (long)attr.c_cc[VMIN];
			context.control.cc[BAKEY_CONTROL_CHARACTER_INTERRUPT] = (long)attr.c_cc[VINTR];
			context.control.cc[BAKEY_CONTROL_CHARACTER_QUIT] = (long)attr.c_cc[VQUIT];
			context.control.cc[BAKEY_CONTROL_CHARACTER_SUSPEND] = (long)attr.c_cc[VSUSP];
		}

		/*
		 * We then update the Bakey terminal.
		 * In our case, this will call our
		 * implementation of term_read, which
		 * will wait until data is available or
		 * the frame timer signal interrupts
		 * the call.
		 */
		if (context.display_updated)
			display_updated = true;

		if (bakey_update(&context) != BAKEY_RESULT_SUCCESS) {

			fprintf(stderr, "Bakey: %s\n", bakey_get_error());
			return 1;
		}

		/*
		 * Next, if the frame timer went off,
		 * we read any pending events and
		 * update the terminal display.
		 */
		if (context.display_updated)
			display_updated = true;

		if (draw) {

			while (SDL_PollEvent(&event))
				process_event(&event);

			if (display_updated) {

				draw_terminal();
				SDL_RenderPresent(renderer);

				display_updated = false;
			}
		}
	}
	return 0;
}

/*
 * Clean up resources used by the main application
 */
static void cleanup(void) {

	if (context.init) bakey_close(&context);
	if (display.cells) free(display.cells);
	if (font_atlas_texture) SDL_DestroyTexture(font_atlas_texture);
	if (renderer) SDL_DestroyRenderer(renderer);
	if (window) SDL_DestroyWindow(window);
	if (init_sdl) SDL_Quit();
}

int main() {

	int code = run();
	cleanup();
	return code;
}
